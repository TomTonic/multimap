// Command gen writes fixed_ptr_gen.go of package page: the Go types of the
// Fixed pages whose values are a word with a pointer. The garbage collector
// knows which words of an object are pointers from the object's type, and the
// page has head and remainder in front of its values, so the type must say
// that its first J words are not pointers and the others are: one type for
// every size class (4, 8, 16, 32, 48 or 64 words) and every J from 1 to one
// less than the words of the class, 166 in all.
//
//	go generate ./internal/page
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
)

func main() {
	words := []int{4, 8, 16, 32, 48, 64}
	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/page/gen; DO NOT EDIT.

package page

import "unsafe"

// ptrObject is the object of a Fixed page whose values are a word with a
// pointer: J words of head and remainder (H), then the values (V).
type ptrObject[T any, H, V any] struct {
	h H
	v V
}

// allocPtr returns a zeroed object of class c whose first j words are no
// pointers and whose other words are values of T, a word with a pointer. It
// returns nil for a class or a j that no page has.
func allocPtr[T any](c, j int) unsafe.Pointer {
	switch c {
`)
	for c, w := range words {
		fmt.Fprintf(&b, "\tcase %d:\n\t\tswitch j {\n", c)
		for j := 1; j < w; j++ {
			fmt.Fprintf(&b, "\t\tcase %d:\n\t\t\treturn unsafe.Pointer(new(ptrObject[T, [%d]uint64, [%d]T]))\n", j, j, w-j)
		}
		b.WriteString("\t\t}\n")
	}
	b.WriteString("\t}\n\treturn nil\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("fixed_ptr_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
